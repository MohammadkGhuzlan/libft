#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*x;

	i = 0;
	x = (unsigned char *)s;
	while (i < n)
	{
		if (*x == c)
		{
			return (x);
		}
		x++;
		i++;
	}
	return (NULL);
}
